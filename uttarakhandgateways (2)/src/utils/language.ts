export type TranslationKey = keyof typeof TRANSLATIONS;

export function getTranslation(key: TranslationKey, language: 'en' | 'hi'): string {
  const item = TRANSLATIONS[key];
  if (!item) return key;
  return item[language] || item.en;
}

// Convert Hindi digits or localized price
export function formatLocalizedPrice(priceDisplay: string, language: 'en' | 'hi'): string {
  if (language !== 'hi') return priceDisplay;
  return priceDisplay
    .replace(/Lakh/gi, 'लाख')
    .replace(/Cr/gi, 'करोड़')
    .replace(/Crore/gi, 'करोड़')
    .replace(/k/gi, 'हजार');
}

